def test_CC1_nielsen_olesen_exact():
    print('CC1  Nielsen–Olesen instability (sympy, linearised model YM EOM)')
    r = dcc.derive_D1_nielsen_olesen()
    ok_scalar = dcc.derive_D1b_scalar_control()
    passed = (r['aligned'] and r['nonvacuous'] and (not r['anti-aligned'])
              and ok_scalar)
    record('CC1', passed, {
        'aligned_gamma2_gB_exact': r['aligned'],
        'wrong_dispersion_fails': r['nonvacuous'],
        'anti_aligned_does_not_grow': not r['anti-aligned'],
        'scalar_control_omega2_pos_gB': ok_scalar,
        'tier': 1})


def test_CC2_savvidy_exact():
    print('CC2  Savvidy one-loop potential (sympy, Hurwitz zeta)')
