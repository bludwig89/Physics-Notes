DL_S_FOR_RESONANT = 1e-4     # late lepton asymmetry needed for resonant keV DM (~ up to 8e-4)


def cp_phase_count(n=3):
    """Physical CP phases in the lepton sector with n Dirac + Majorana neutrinos.
    PMNS Dirac phases: (n-1)(n-2)/2 ; Majorana phases: n-1 ; (heavy-sector phases
    additionally feed leptogenesis)."""
    dirac = (n - 1) * (n - 2) // 2
    majorana = n - 1
    return {"n_generations": n, "pmns_dirac_phases": dirac, "majorana_phases": majorana,
            "total_low_energy_phases": dirac + majorana,
            "cp_available": bool(dirac + majorana > 0)}


