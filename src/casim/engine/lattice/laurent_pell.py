#: A direction with Q-linearly independent components.  Any such lambda works;
#: this one is fixed so the numbers in the finding are reproducible.  It is NOT
#: a physical constant and matches no registry value.
LAMBDA: Tuple[float, float, float] = (1.0, math.sqrt(2.0), math.sqrt(3.0))

_I = laurent_const(0, 1)
_MINUS_I = laurent_const(0, -1)
_ONE = laurent_const(1)


# ══════════════════════════════════════════════════════════════════
#  The two-sided width
# ══════════════════════════════════════════════════════════════════

def support(f: Laurent, sign: int = 1) -> float:
    """h_f(sign * lambda) = max over the support of <m, sign*lambda>."""
    if not f:
        raise ValueError("the support function of 0 is undefined; handle b = 0 separately")
    return max(sign * (m[0] * LAMBDA[0] + m[1] * LAMBDA[1] + m[2] * LAMBDA[2])
               for m in f)


def width(f: Laurent) -> Optional[float]:
    """D(f) = h_f(lambda) + h_f(-lambda); None for f = 0.

    This is the replacement for Dubickas-Steuding's degree.  It is additive
    under multiplication (L1) and vanishes exactly on units (L2) — the property
    `deg f = 0 => f constant` has in a Laurent ring.
    """
    if not f:
        return None
    return support(f, 1) + support(f, -1)


def leading(f: Laurent, sign: int = 1):
    """(exponent, coefficient) of the unique lambda-maximal monomial."""
    m = max(f, key=lambda m: sign * (m[0] * LAMBDA[0] + m[1] * LAMBDA[1]
                                     + m[2] * LAMBDA[2]))
    return m, f[m]


def unique_maximiser_gap(f: Laurent, sign: int = 1) -> float:
    """Gap between the top two values of <m, sign*lambda>; +inf if one monomial.

    Reported rather than assumed: L1 is only true because this gap is strictly
    positive, and Q-independence is what guarantees it.
    """
    vals = sorted((sign * (m[0] * LAMBDA[0] + m[1] * LAMBDA[1] + m[2] * LAMBDA[2])
                   for m in f), reverse=True)
    return math.inf if len(vals) < 2 else vals[0] - vals[1]


def is_unit(f: Laurent) -> bool:
    """A unit of R is exactly a monomial with nonzero coefficient."""
    return len(f) == 1


def _star_is(f: Laurent, sign: int) -> bool:
    """f* == sign * f."""
    return f.star() == (f if sign > 0 else f.scale((_F(-1), _F(0))))


def _mul(xi, eta, N: Laurent):
    """Multiplication in R[X]/(X^2 - N), elements written (a, b) = a + bX."""
    a1, b1 = xi
    a2, b2 = eta
    return (a1 * a2 + (b1 * b2) * N, a1 * b2 + b1 * a2)


def _tower(nmax: int, sign: str = "+"):
    """A^1 .. A^nmax as Pell pairs."""
    u, N = bcc_u(sign), bcc_discriminant(sign)
    A = (u, _MINUS_I)
    out, cur = [], (_ONE, Laurent())
    for _ in range(nmax):
        cur = _mul(cur, A, N)
        out.append(cur)
    return out, u, N


# ══════════════════════════════════════════════════════════════════
#  L1 / L2 — the replacement for "deg 0 => constant"
# ══════════════════════════════════════════════════════════════════

def check_L1_genericity(nmax: int = 6, sign: str = "+") -> Dict[str, object]:
    """The lambda-maximiser is unique, so h is additive and lc multiplicative.

    Both are checked on real elements of the tower, not asserted: h(fg) - h(f)
    - h(g) must be 0 and lc(fg) - lc(f)lc(g) must be 0.
    """
    tower, u, N = _tower(max(nmax, 2), sign)
    gaps, hadd, lcmul = [], [], []
    probes = [u, N] + [x for pair in tower[:3] for x in pair if x]
    for f in probes:
        gaps.append(unique_maximiser_gap(f, 1))
        gaps.append(unique_maximiser_gap(f, -1))
    for f in probes[:4]:
        for g in probes[:4]:
            fg = f * g
            if not fg:
                continue
            hadd.append(abs(support(fg) - support(f) - support(g)))
            _, cf = leading(f)
            _, cg = leading(g)
            _, cfg = leading(fg)
            prod = (cf[0] * cg[0] - cf[1] * cg[1], cf[0] * cg[1] + cf[1] * cg[0])
            lcmul.append(abs(float(cfg[0] - prod[0])) + abs(float(cfg[1] - prod[1])))
    return {
        "lambda": LAMBDA,
        "min_maximiser_gap": float(min(g for g in gaps if g != math.inf)),
        "max_h_additivity_residual": float(max(hadd)),
        "max_lc_multiplicativity_residual": float(max(lcmul)),
        "n_probes": len(probes),
    }


def check_L2_width_detects_units(sign: str = "+") -> Dict[str, object]:
    """D(f) = 0 iff f is a monomial iff f is a unit — and (*) is FALSE here.

    The second half is the point: `1 + w^-1` has ordinary Laurent degree 0 and
    is NOT a unit, which is exactly why Dubickas-Steuding does not transfer as
    written.  D assigns it a positive width, so D does the job deg cannot.
    """
    from casim.engine.lattice.time_signature import laurent_mono
    u = bcc_u(sign)
    counterexample = laurent_mono((0, 0, 0)) + laurent_mono((-1, 0, 0))
    monomials = [laurent_mono(e) for e in ((0, 0, 0), (2, -1, 3), (-1, -1, -1))]
    return {
        "monomial_widths": [width(m) for m in monomials],
        "all_monomials_zero_width": all(abs(width(m)) < 1e-12 for m in monomials),
        "all_monomials_are_units": all(is_unit(m) for m in monomials),
        # the counterexample that breaks the imported theorem's hypothesis
        "counterexample": "1 + w1^-1",
        "counterexample_is_unit": is_unit(counterexample),
        "counterexample_width": float(width(counterexample)),
        "width_separates_it": bool(width(counterexample) > 1e-12),
        "u_width": float(width(u)),
        "u_is_unit": is_unit(u),
    }


# ══════════════════════════════════════════════════════════════════
#  L3 — unitarity => centrally symmetric Newton polytopes
# ══════════════════════════════════════════════════════════════════

def check_L3_central_symmetry(nmax: int = 6, sign: str = "+") -> Dict[str, object]:
    """a* = a and b* = -b, hence h(lambda) = h(-lambda) and D = 2h >= 0.

    This is the ingredient Dubickas-Steuding has no analogue of, and it is what
    makes the Laurent descent close.  It comes from UNITARITY, not from det = 1:
    B* = B^-1 = sigma(B) for a unitary B with unit determinant.
    """
    tower, _, _ = _tower(nmax, sign)
    rows = []
    for n, (a, b) in enumerate(tower, start=1):
        rows.append({
            "n": n,
            "a_self_adjoint": _star_is(a, +1),
            "b_anti_self_adjoint": _star_is(b, -1) if b else True,
            "a_symmetry_residual": float(abs(support(a, 1) - support(a, -1))),
            "b_symmetry_residual": (float(abs(support(b, 1) - support(b, -1)))
                                    if b else 0.0),
        })
    return {
        "rows": rows,
        "all_a_self_adjoint": all(r["a_self_adjoint"] for r in rows),
        "all_b_anti_self_adjoint": all(r["b_anti_self_adjoint"] for r in rows),
        "max_symmetry_residual": float(max(max(r["a_symmetry_residual"],
                                               r["b_symmetry_residual"])
                                           for r in rows)),
    }


