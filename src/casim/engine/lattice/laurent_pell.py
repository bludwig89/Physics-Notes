def check_L4_h_relation(nmax: int = 6, sign: str = "+") -> Dict[str, object]:
    """h_a = h_b + c, i.e. D(a) = D(b) + D(u), for every solution with b != 0."""
    tower, u, N = _tower(nmax, sign)
    c = support(u)
    rows = [{"n": n, "D_a": width(a), "D_b": width(b) or 0.0,
             "residual": float(abs(width(a) - (width(b) or 0.0) - 2 * c))}
            for n, (a, b) in enumerate(tower, start=1)]
    return {"c": float(c), "D_u": float(width(u)), "rows": rows,
            "max_residual": float(max(r["residual"] for r in rows))}


def check_L5_leading_sign(nmax: int = 6, sign: str = "+") -> Dict[str, object]:
    """lc(a) = +- i lc(b) lc(u), so exactly one of b*u +- a*i cancels at the top."""
    tower, u, N = _tower(nmax, sign)
    c = support(u)
    rows = []
    for n, (a, b) in enumerate(tower, start=1):
        if not b:
            continue
        hb = support(b)
        bp = b * u + a * _I
        bpp = b * u - a * _I
        tops = []
        for x in (bp, bpp):
            tops.append(None if not x else support(x))
        cancels = [(t is None) or (t < hb + c - 1e-9) for t in tops]
        rows.append({"n": n, "cancels": cancels,
                     "exactly_one": bool(sum(cancels) == 1)})
    return {"rows": rows,
            "always_exactly_one": all(r["exactly_one"] for r in rows)}


def check_L6_product_identity(nmax: int = 6, sign: str = "+") -> Dict[str, object]:
    """b' b'' = 1 + b^2 exactly, and D(1 + b^2) <= 2 D(b) by central symmetry."""
    tower, u, N = _tower(nmax, sign)
    rows = []
    for n, (a, b) in enumerate(tower, start=1):
        if not b:
            continue
        bp, bpp = b * u + a * _I, b * u - a * _I
        target = _ONE + b * b
        db = width(b) or 0.0
        d_target = width(target)
        rows.append({
            "n": n,
            "identity_exact": bool((bp * bpp) == target),
            "D_b": db,
            "D_1_plus_b2": d_target,
            "bounded_by_2Db": bool(d_target is None or d_target <= 2 * db + 1e-9),
        })
    return {"rows": rows,
            "all_identities_exact": all(r["identity_exact"] for r in rows),
            "all_bounded": all(r["bounded_by_2Db"] for r in rows)}


def check_L7_descent(nmax: int = 7, sign: str = "+") -> Dict[str, object]:
    """D drops by at least D(u) = 2c per step, whenever D(b) > 0.

    The hypothesis D(b) > 0 is not decoration: at D(b) = 0 we are in the base
    case, 1 + b^2 = 0, and L6's product identity degenerates.  L8 handles it.
    """
    tower, u, N = _tower(nmax, sign)
    c = support(u)
    rows = []
    for n, (a, b) in enumerate(tower, start=1):
        db = width(b)
        if db is None or db <= 1e-12:
            rows.append({"n": n, "base_case": True})
            continue
        bp, bpp = b * u + a * _I, b * u - a * _I
        ds = [width(x) for x in (bp, bpp)]
        finite = [x for x in ds if x is not None]
        best = min(finite) if finite else 0.0
        rows.append({
            "n": n, "base_case": False, "D_b": db,
            "D_after": best,
            "drop": float(db - best),
            "drop_is_2c": bool(abs((db - best) - 2 * c) < 1e-9),
            "strict": bool(best < db - 1e-9),
        })
    live = [r for r in rows if not r["base_case"]]
    return {"c": float(c), "rows": rows,
            "n_live": len(live),
            "all_strict": all(r["strict"] for r in live),
            "all_drop_exactly_2c": all(r["drop_is_2c"] for r in live)}


def check_L8_base_case(sign: str = "+") -> Dict[str, object]:
    """D(b) = 0 forces xi in {+-1, +-A^{+-1}} — the descent's landing set.

    Two sub-facts, both checked: an anti-self-adjoint monomial is a purely
    imaginary CONSTANT; and u is not a difference of two monomials, which is
    what rules out beta^2 != 1.
    """
    from casim.engine.lattice.time_signature import laurent_mono
    u = bcc_u(sign)
    off_origin = [laurent_mono(e, (3, 5)) for e in ((1, 0, 0), (2, -1, 3))]
    pure_imag = laurent_mono((0, 0, 0), (0, 7))
    real_const = laurent_mono((0, 0, 0), (7, 0))
    return {
        "u_monomial_count": len(u),
        "u_is_difference_of_two_monomials": bool(len(u) <= 2),
        "off_origin_monomials_anti_self_adjoint":
            [bool(_star_is(m, -1)) for m in off_origin],
        "purely_imaginary_constant_is_anti_self_adjoint": bool(_star_is(pure_imag, -1)),
        "real_constant_is_not": bool(not _star_is(real_const, -1)),
        "landing_set": "{+-1, +-A, +-A^-1}",
    }


