def check_dirac_composite_single_generator(
        L: int = 4, n: int = 4, m: float = 0.37, sign: str = "+",
        mode_index: Tuple[int, int, int] = (1, 1, 0),
        direct_n_offset: int = 0,
) -> Dict[str, object]:
    """Iterating the production stepper n times == D_k^n applied once.

    This is F313 sec.9's own setting (mass != 0, both chirality branches
    coupled — the composite whose SECOND commuting flow V is what F315
    killed) but a different question: not "what else commutes with the
    joint object" but "is the joint object's own history the power series
    of ONE matrix". A single mode is isolated exactly (a plane wave is a
    delta in Fourier space), so the comparison is between two INDEPENDENT
    computations of the same number: the engine's real-space stepper run
    n times and FFT'd, versus `build_D_k_matrix` applied directly n times
    to the initial Fourier amplitude.

    CAVEAT (review pass, 2026-08-20): "independent" here means independently
    *coded* (real-space split-step vs. an explicit matrix build), not
    independent at the level of physical primitives -- both functions call
    the same `_kinetic_n`/`bcc.bcc_unitary` machinery underneath. The
    residual mainly certifies that this module's FFT round-trip and the
    stepper's own bookkeeping are correct; the part of this check that
    actually bears on "is this a single generator" is
    `stepper_has_no_branch_local_dt` (the signature has no per-branch dt),
    not the small residual by itself.
    """
    assert abs(m) < 1.0, "need a genuinely massive (coupled) composite"
    KX, KY, KZ = make_kgrid_3d(L, L, L)
    ix, iy, iz = mode_index
    kx, ky, kz = float(KX[ix, iy, iz]), float(KY[ix, iy, iz]), float(KZ[ix, iy, iz])

    # An arbitrary complex amplitude at that one mode, all four components
    # populated so both chirality branches start nonzero (chi is genuinely
    # excited too, not just carried passively by the mass coupling).
    psi0 = xp.array([1.0 + 0.3j, -0.4 + 0.2j, 0.15 - 0.6j, 0.5 + 0.1j],
                     dtype=complex)

    # -- independent computation 1: the algebraic matrix, iterated directly
    D = build_D_k_matrix(kx, ky, kz, m, sign=sign)
    unitarity_residual = float(
        xp.max(xp.abs(D.conj().T @ D - xp.eye(4, dtype=complex))))
    psi_direct = psi0.copy()
    # `direct_n_offset` (control only): deliberately iterate D_k a DIFFERENT
    # number of times than the engine actually ticks, so the comparison below
    # is exercised against a genuine mismatch rather than trivially agreeing
    # regardless of n.
    n_direct = max(n + direct_n_offset, 0)
    for _ in range(n_direct):
        psi_direct = D @ psi_direct

    # -- independent computation 2: the production real-space stepper
    def _delta_field(amp):
        F = xp.zeros((L, L, L), dtype=complex)
        F[ix, iy, iz] = amp
        return _fft.ifftn(F)

    eta_u = _delta_field(psi0[0])
    eta_d = _delta_field(psi0[1])
    chi_u = _delta_field(psi0[2])
    chi_d = _delta_field(psi0[3])
    for _ in range(n):
        eta_u, eta_d, chi_u, chi_d = dirac_step_3d_bcc_splitstep(
            eta_u, eta_d, chi_u, chi_d, m=m, dt=1.0, sign=sign)

    psi_engine = xp.array([
        _fft.fftn(eta_u)[ix, iy, iz],
        _fft.fftn(eta_d)[ix, iy, iz],
        _fft.fftn(chi_u)[ix, iy, iz],
        _fft.fftn(chi_d)[ix, iy, iz],
    ])

    residual = float(xp.max(xp.abs(psi_engine - psi_direct)))

    # The stepper's own signature admits one shared dt/tick for the whole
    # four-component object -- no per-branch dt parameter exists to give
    # eta and chi independent rates.
    sig = inspect.signature(dirac_step_3d_bcc_splitstep)
    param_names = set(sig.parameters)
    branch_local_time_params = {p for p in param_names
                                 if p not in ("eta_u", "eta_d", "chi_u",
                                              "chi_d", "m", "dt", "sign")}

    out = {
        "mode": (kx, ky, kz), "n": n, "m": m, "sign": sign,
        "D_unitarity_residual": unitarity_residual,
        "off_diagonal_coupling_nonzero": bool(abs(m) > 0
                                               and xp.max(xp.abs(D[0:2, 2:4])) > 0),
        "psi_direct": [complex(x) for x in psi_direct],
        "psi_engine": [complex(x) for x in psi_engine],
        "max_residual": residual,
        "stepper_params": sorted(param_names),
        "stepper_has_no_branch_local_dt": branch_local_time_params == set(),
    }
    assert out["D_unitarity_residual"] < 1e-10, out
    assert out["off_diagonal_coupling_nonzero"], (
        f"mass coupling between branches is not actually engaged: {out}")
    assert out["max_residual"] < 1e-8, (
        "iterating the production stepper n times does not reproduce D_k^n "
        f"applied once -- the joint object is NOT a single generator: {out}")
    assert out["stepper_has_no_branch_local_dt"], (
        "the production stepper exposes a per-branch time parameter, which "
        f"would make eta and chi independently clockable: {out}")
    return out


# ══════════════════════════════════════════════════════════════════
