class _ProbeChannel(Channel):
    """A trivial channel used only to exercise the engine's step loop.

    Records how many times ``step`` was actually called on it within a
    single ``Simulation.step()`` call — the thing G1 needs to see directly,
    not infer.
    """
    type_name = "time_single_generator_probe"

    def __init__(self, name=None, dt_native=1.0, **config):
        super().__init__(name=name, dt_native=dt_native, **config)
        self.dt_native = dt_native
        self.calls = 0

    def init_state(self, lattice, rng):
        return {"calls": 0}

    def step(self, state, lattice, context=None, rng=None):
        self.calls += 1
        return {"calls": self.calls}

    def energy(self, state) -> float:
        return float(state["calls"])


def check_engine_single_global_clock(n_ticks: int = 3) -> Dict[str, object]:
    """The engine has exactly one persisted time counter, and nothing hides a second.

    Three legs, all asserted:

      (a) ``Clock`` (`casim.engine.core.clock`) persists exactly one
          time-bookkeeping field, ``tick``; ``time`` is a *derived* property
          (``tick * dt``), not independent state. ``timings`` is per-channel
          RECONCILIATION data (how many sub-steps each channel takes within
          one tick), not a second clock.
      (b) ``Channel`` (`casim.engine.core.channel`) carries no field that
          tracks elapsed time on its own — no channel can drift out of step
          with the engine's one counter because none HAS a counter.
      (c) A live two-channel ``Simulation``, one channel at the native
          resolution and one at twice it (``dt_native`` half the global
          ``dt``, forcing ``n_sub == 2``), is stepped ``n_ticks`` times.
          ``Simulation.tick`` advances by exactly ``n_ticks``, and the finer
          channel's own call count is exactly ``2 * n_ticks`` — a fixed,
          engine-determined multiple of the SAME outer count, not a
          separately advancing number.
    """
    clock_fields = {f.name for f in dataclasses.fields(Clock)}
    # `resolved_mode` and `mode` are configuration, not elapsed-time state;
    # `timings` is reconciliation data (leg (a)'s point); `tick` is the one
    # elapsed-time counter.
    time_state_fields = {"tick"}
    non_time_fields = clock_fields - time_state_fields - {
        "mode", "resolved_mode", "timings", "dt"}

    # Channel exposes several *unrelated* optional hooks (T_munu, block_spin,
    # consumes/provides for the bus, etc.) -- G1's claim is narrower and
    # sharper than "Channel has no other attributes": none of those hooks is
    # a TIME-tracking field, i.e. none of the names an independent clock
    # would need is present on the class at all.
    _time_like_names = {"tick", "time", "clock", "n_sub", "step_count",
                         "elapsed", "t", "dt_elapsed"}
    channel_stray_time_fields = _time_like_names & set(dir(Channel))

    lattice = LatticeSpec(L=4, dims=3, topology="cubic", c_lat=c_lat)
    fast = _ProbeChannel(name="fast", dt_native=0.5)
    slow = _ProbeChannel(name="slow", dt_native=1.0)
    # mode="strict" is what actually turns on sub-cycling (n_sub > 1); the
    # default "auto" mode falls back to "legacy" (forces n_sub=1,
    # desynchronised) precisely to stay bit-identical to pre-P3.2 runs, which
    # would hide the very thing G1(c) needs to see.
    sim = Simulation(lattice=lattice, channels=[slow, fast], seed=0,
                      name="G1-single-clock-probe", clock={"mode": "strict"})
    sim.step(n_ticks)

    fast_calls = sim.states["fast"]["calls"]
    slow_calls = sim.states["slow"]["calls"]
    n_sub_fast = sim.clock.n_sub("fast")

    out = {
        "clock_dataclass_fields": sorted(clock_fields),
        "clock_has_exactly_one_time_state_field": time_state_fields <= clock_fields
        and len(time_state_fields) == 1,
        "clock_stray_fields": sorted(non_time_fields),
        "channel_carries_no_time_field": channel_stray_time_fields == set(),
        "channel_stray_fields": sorted(channel_stray_time_fields),
        "n_ticks_requested": n_ticks,
        "sim_tick_after": sim.tick,
        "n_sub_fast": n_sub_fast,
        "slow_calls": slow_calls,
        "fast_calls": fast_calls,
        "fast_calls_is_deterministic_multiple":
            fast_calls == n_sub_fast * n_ticks,
        "slow_calls_equals_tick": slow_calls == sim.tick,
    }
    assert out["clock_has_exactly_one_time_state_field"], (
        f"Clock carries more than one persisted time-state field: {out}")
    assert out["channel_carries_no_time_field"], (
        f"Channel exposes its own time-tracking attribute(s): {out}")
    assert out["sim_tick_after"] == n_ticks, (
        f"Simulation.tick did not advance by exactly n_ticks: {out}")
    assert out["slow_calls_equals_tick"], (
        "the slow (native-resolution) channel's own call count drifted from "
        f"the single global tick counter: {out}")
    assert out["fast_calls_is_deterministic_multiple"], (
        "the finer channel's sub-stepping is NOT a deterministic multiple of "
        f"the one global tick — it would be a second, free-running clock: {out}")
    return out


