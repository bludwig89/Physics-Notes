def check_all(n_ticks: int = 3, n_dirac: int = 4, m: float = 0.37,
              break_single_clock: bool = False,
              break_composite_single_generator: bool = False) -> Dict[str, object]:
    """Registry entry point.

    ``break_single_clock`` (control): forces the probe channel's own call
        counter to be read against a WRONG multiple of the tick count
        (``n_ticks`` instead of ``n_sub * n_ticks``), which must go red
        whenever ``n_sub != 1`` -- exercising exactly the failure mode G1
        exists to catch (a channel silently running on its own clock).
    ``break_composite_single_generator`` (control): compares the engine's
        n-tick result against ``D_k`` applied only ``n-1`` times, which must
        go red -- a sanity check that G2's comparison is not vacuously
        passing regardless of n.
    """
    out = {}
    if break_single_clock:
        try:
            g1 = check_engine_single_global_clock(n_ticks=n_ticks)
            # If n_sub happens to be 1 the control cannot separate; force a
            # mismatched read directly instead of relying on the assertion.
            assert g1["fast_calls"] == n_ticks, (
                "CONTROL break_single_clock: asserting the WRONG relation "
                f"(fast_calls == n_ticks) which must fail when n_sub != 1: {g1}")
            out["G1_engine_single_global_clock"] = g1
        except AssertionError as exc:
            raise AssertionError(f"[control break_single_clock RED, as required] {exc}")
    else:
        out["G1_engine_single_global_clock"] = check_engine_single_global_clock(
            n_ticks=n_ticks)

    if break_composite_single_generator:
        # Deliberately compare n ticks of the engine's own stepper against
        # n-1 applications of D_k -- the check's own internal assertion
        # (max_residual < 1e-8) must go RED. If it didn't, the comparison
        # would be vacuous (agreeing regardless of n).
        try:
            out["G2_dirac_composite_single_generator"] = (
                check_dirac_composite_single_generator(
                    n=n_dirac, m=m, direct_n_offset=-1))
        except AssertionError as exc:
            raise AssertionError(
                f"[control break_composite_single_generator RED, as required] {exc}")
        else:
            raise AssertionError(
                "CONTROL break_composite_single_generator: comparing n engine "
                "ticks against n-1 applications of D_k did NOT go red -- the "
                "comparison is vacuous and proves nothing about n")
    else:
        out["G2_dirac_composite_single_generator"] = (
            check_dirac_composite_single_generator(n=n_dirac, m=m))

    out["n_checks"] = 2
    out["verdict"] = (
        "No second candidate generator exists to close the '+1' against: "
        "BDPT uniqueness (cited, not re-derived) leaves no second solution "
        "to start from, and F313 Sec.3-4's own commutant closure (cited, not "
        "re-derived) leaves no room for one to hide as a symmetry of the "
        "first. The one remaining input -- that the dynamics is a single "
        "map iterated -- is the same posit that defines a QCA at all, "
        "grounded here in the live engine (G1) and in the model's own "
        "coupled two-branch composite (G2, F313 sec.9's own object)."
    )
    return out


