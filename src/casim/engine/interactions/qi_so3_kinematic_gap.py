# Deterministic sampling (house convention: no RNG — Fibonacci-sphere axes,
# as in F289's rotor_phase_axis_independence / F330's _fibonacci_axes).
# ======================================================================
def _fibonacci_axes(n: int):
    golden = math.pi * (3.0 - math.sqrt(5.0))
    axes = []
    for i in range(n):
        z = 1.0 - 2.0 * (i + 0.5) / n
        r = math.sqrt(max(0.0, 1.0 - z * z))
        th = golden * i
        axes.append((r * math.cos(th), r * math.sin(th), z))
    return axes


def _generic_angles(n: int):
    """Angles deliberately offset from O_h's own characteristic angles
    (0, pi/2, pi, 3pi/2, 2pi/3, 4pi/3, ...) so the sweep tests CONTINUOUS
    rotations genuinely outside the discrete point group, not a relabelling
    of its 48 elements."""
    return [2.0 * math.pi * (j + 0.5) / n + 0.193723 for j in range(n)]


def rodrigues(axis, angle: float) -> np.ndarray:
    """The SO(3) rotation matrix for a continuous (axis, angle) pair —
    deliberately independent of O_h; any real axis and any real angle."""
    n = np.asarray(axis, dtype=float)
    n = n / np.linalg.norm(n)
    K = np.array([[0.0, -n[2], n[1]],
                  [n[2], 0.0, -n[0]],
                  [-n[1], n[0], 0.0]])
    I3 = np.eye(3)
    return I3 + math.sin(angle) * K + (1.0 - math.cos(angle)) * (K @ K)


def _dot_sigma(v) -> np.ndarray:
    return v[0] * SX + v[1] * SY + v[2] * SZ


