# K1 — idealised H_W = k.sigma/sqrt(3): EXACT continuous SO(3) covariance,
#      via the SAME rotor object F289/F330 use.
# ======================================================================
def idealized_weyl_continuous_covariance(n_axes: int = 8, n_angles: int = 7,
                                         n_k: int = 5) -> Dict[str, Any]:
    """U(R) (k.sigma) U(R)^dagger == (Rk).sigma, for CONTINUOUS R (Rodrigues,
    not restricted to O_h's 48 elements), using su2_rotor(angle/2, axis) —
    F289/F330's own rotor function. An exact SU(2)-adjoint identity: should
    hold at the round-off floor for every swept (axis, angle, k), including
    axes/angles well outside O_h."""
    axes = _fibonacci_axes(n_axes)
    angles = _generic_angles(n_angles)
    k_axes = _fibonacci_axes(n_k)
    worst = 0.0
    n_checked = 0
    for axis in axes:
        for angle in angles:
            R = rodrigues(axis, angle)
            U = _rotor_for_physical_angle(angle, axis)
            for kdir in k_axes:
                k = np.asarray(kdir, dtype=float) * 0.37   # fixed nonzero |k|
                lhs = U @ _dot_sigma(k) @ U.conj().T
                rhs = _dot_sigma(R @ k)
                worst = max(worst, float(np.linalg.norm(lhs - rhs)))
                n_checked += 1
    return {"n_axes": n_axes, "n_angles": n_angles, "n_k": n_k,
            "n_checked": n_checked, "worst_residual": worst}


# ======================================================================
# K2 — the ACTUAL shipped BCC walk (bcc._bcc_uvec), extending F344's
#      48-element leg C8 to a swept family of GENERIC continuous rotations.
# ======================================================================
def shipped_walk_continuous_covariance_decades(
        axis=(0.4082482905, 0.4082482905, -0.8164965809),
        angle: float = 1.1071487178,
        decades: Tuple[float, ...] = (1e-1, 1e-2, 1e-3, 1e-4),
        branch: str = '+') -> Dict[str, Any]:
    """F344 Sec.3-4: the shipped leading-order n(k) is n = S k/sqrt(3) + O(k^2)
    with S = diag(p), p = (+1, -1, +1) on the '+' branch (F344's own
    convention). Hence for a continuous rotation R (not merely an O_h
    element), n(Rk) = (S R S^-1) n(k) + O(k^2) — pure linear algebra once the
    branch bookkeeping is applied, the SAME mechanism F344 verified only for
    the discrete C3 rotation (its leg C8). This function sweeps k down four
    decades at one fixed GENERIC (non-O_h) axis/angle and measures the
    relative defect ||n(Rk) - (S R S^-1) n(k)|| / |n(k)|, which F344's own
    closed-form argument (O(k^2) absolute, O(k) relative) predicts shrinks
    linearly in |k| — i.e. decade ratios converging to 10, exactly as F344's
    leg C8 found for its one (discrete) rotation."""
    # F344 Sec.3: p = (+1, -s, +1), s = +1 on '+' (giving diag(1,-1,1)) and
    # s = -1 on '-' (giving diag(1,1,1), the identity) -- NOT diag(-1,1,-1),
    # which was this module's own bug until the F379 review caught it
    # (branch='-' failed at O(1), never exercised by the gate's default).
    S = np.diag([1.0, -1.0, 1.0]) if branch == '+' else np.diag([1.0, 1.0, 1.0])
    R = rodrigues(axis, angle)
    Rp = S @ R @ S  # S^-1 = S for a diagonal +-1 matrix
    ax = np.asarray(axis, dtype=float) / np.linalg.norm(axis)
    defects = []
    for mag in decades:
        k = ax * mag
        kR = R @ k
        _, nx, ny, nz = _bcc_uvec(k[0], k[1], k[2], sign=branch)
        n_k = np.array([nx, ny, nz])
        _, nx2, ny2, nz2 = _bcc_uvec(kR[0], kR[1], kR[2], sign=branch)
        n_Rk = np.array([nx2, ny2, nz2])
        predicted = Rp @ n_k
        defect = float(np.linalg.norm(n_Rk - predicted))
        rel = defect / max(float(np.linalg.norm(n_k)), 1e-300)
        defects.append({"mag": float(mag), "defect_abs": defect,
                        "defect_relative": rel})
    ratios = [defects[i]["defect_relative"] / defects[i + 1]["defect_relative"]
              for i in range(len(defects) - 1)]
    return {"axis": tuple(float(a) for a in ax), "angle": float(angle),
            "branch": branch, "decades": defects, "decade_ratios": ratios}


# ======================================================================
# K3 — CONTROL: an UNCORRELATED spin rotation breaks K1's identity at O(1).
# ======================================================================
def uncorrelated_rotor_control(axis=(0.0, 0.0, 1.0), angle: float = 1.7,
                               wrong_axis=(1.0, 0.0, 0.0),
                               wrong_angle: float = 0.4) -> Dict[str, Any]:
    """Rotate k by R(axis, angle) but transport spin via an UNCORRELATED
    rotor U(wrong_axis, wrong_angle) instead of U(axis, angle). Demonstrates
    K1 is a real "same rotation" statement (Postulate 1's own "rather than
    some other, uncorrelated unitary") and not a vacuous SU(2)-closure fact
    that would pass for any pair of unitaries."""
    k = np.array([0.11, 0.23, -0.17])
    R = rodrigues(axis, angle)
    U_correct = _rotor_for_physical_angle(angle, axis)
    U_wrong = _rotor_for_physical_angle(wrong_angle, wrong_axis)
    rhs = _dot_sigma(R @ k)
    lhs_correct = U_correct @ _dot_sigma(k) @ U_correct.conj().T
    lhs_wrong = U_wrong @ _dot_sigma(k) @ U_wrong.conj().T
    return {"residual_correct_rotor": float(np.linalg.norm(lhs_correct - rhs)),
            "residual_uncorrelated_rotor": float(np.linalg.norm(lhs_wrong - rhs))}


