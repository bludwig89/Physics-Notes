# D3 — dual sine-Gordon: Debye mass + BPS dual-string tension
# ------------------------------------------------------------------
def derive_D3_sine_gordon():
    kappa, zfug = sp.symbols('kappa z', positive=True)
    chi = sp.Function('chi')
    xi = sp.Symbol('xi', real=True)

    # (a) mass: expand 2z(1-cos chi) = z chi^2 + O(chi^4); with kinetic
    #     (kappa/2)(d chi)^2 the quadratic Lagrangian is
    #     (kappa/2)[(d chi)^2 + (2z/kappa) chi^2]  ->  m_D^2 = 2z/kappa.
    pot = 2 * zfug * (1 - sp.cos(sp.Symbol('chi_s')))
    quad = sp.series(pot, sp.Symbol('chi_s'), 0, 3).removeO()
    mD2 = sp.simplify(2 * quad / sp.Symbol('chi_s')**2 / kappa)
    ok_mass = sp.simplify(mD2 - 2 * zfug / kappa) == 0

    # (b) BPS kink tension (Bogomolny completion, same trick as F86 CD1):
    #     E = Int (kappa/2) chi'^2 + 2z(1-cos chi)
    #       = Int (1/2)(sqrt(kappa) chi' - sqrt(4z(1-cos chi)))^2
    #         + sqrt(kappa) chi' sqrt(4z(1-cos chi))
    #     square vanishes on the Bogomolny eq; the cross term is a total
    #     derivative: sigma = Int_0^{2pi} sqrt(4 kappa z (1-cos chi)) dchi
    chi_s = sp.Symbol('chi_s')
    integrand = sp.sqrt(4 * kappa * zfug * (1 - sp.cos(chi_s)))
    # half-angle identity 1 - cos = 2 sin^2(chi/2); sin(chi/2) >= 0 on [0,2pi]
    half = sp.sqrt(8 * kappa * zfug) * sp.sin(chi_s / 2)
    ok_halfangle = sp.simplify(integrand**2 - half**2) == 0
    sigma_dual = sp.integrate(half, (chi_s, 0, 2 * sp.pi))
    ok_sigma = ok_halfangle and \
        sp.simplify(sigma_dual - 8 * sp.sqrt(2 * kappa * zfug)) == 0

    # (c) Bogomolny equation closure: chi(xi) = 4 atan(exp(m xi)) solves
    #     sqrt(kappa) chi' = sqrt(4z(1-cos chi)) with m = sqrt(2z/kappa)
    m = sp.sqrt(2 * zfug / kappa)
    kink = 4 * sp.atan(sp.exp(m * xi))
    lhs = sp.sqrt(kappa) * sp.diff(kink, xi)
    rhs = sp.sqrt(4 * zfug * (1 - sp.cos(kink)))
    ok_kink = sp.simplify(sp.trigsimp(lhs - rhs)) == 0

    return {'mD2_2z_over_kappa': ok_mass, 'sigma_dual_8sqrt2kz': ok_sigma,
            'kink_solves_bogomolny': ok_kink}


