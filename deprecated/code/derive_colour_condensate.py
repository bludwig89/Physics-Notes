# D2 — Savvidy one-loop potential via Hurwitz zeta (exact coefficients)
# ------------------------------------------------------------------
def derive_D2_savvidy():
    """Charged-vector Landau sum, zeta_H-regularised.

    Per 2D Landau level of mass^2 M^2 (degeneracy gB/2pi per area) the
    regularised (1+1)D vacuum-energy density carries the universal term
    -(M^2/8pi) ln(mu^2/M^2); summing M^2_{n,s} = gB(2n+1+2s) over n with
    zeta_H(-1, a) = -B_2(a)/2 gives the exact ln(gB) coefficient."""
    n, a = sp.symbols('n a', positive=True)

    # zeta_H(-1, a) = -B_2(a)/2 (Bernoulli)  — sympy closed form
    zH = lambda aa: sp.zeta(-1, aa)
    s_plus = 2 * zH(sp.Rational(3, 2))      # sum over n of (2n+3), s=+1
    s_minus = 2 * zH(sp.Rational(-1, 2))    # sum over n of (2n-1), s=-1
    total = sp.simplify(s_plus + s_minus)
    ok_sum = sp.simplify(total + sp.Rational(11, 6)) == 0   # = -11/6 exactly

    # log coefficient of dV: (g^2 B^2/16 pi^2) * (-(total)) * ln(gB)
    log_coeff = sp.simplify(-(total) / (16 * sp.pi**2))
    ok_coeff = sp.simplify(log_coeff - sp.Rational(11, 96) / sp.pi**2) == 0

    # minimum: V = B^2/2 + c g^2 B^2 (ln(gB/mu^2) - 1/2), c = 11/96pi^2
    c, mu = sp.symbols('c mu', positive=True)
    Bv = sp.Symbol('B_v', positive=True)
    V = Bv**2 / 2 + c * g**2 * Bv**2 * (sp.log(g * Bv / mu**2) - sp.Rational(1, 2))
    dV = sp.diff(V, Bv)
    Bmin = sp.solve(sp.Eq(dV, 0), Bv)
    Bmin = [s for s in Bmin if s != 0][0]
    Vmin = sp.simplify(V.subs(Bv, Bmin))
    # exact: B_min = (mu^2/g) exp(-1/(2 c g^2)), V(B_min) = -c g^2 B_min^2 / ... < 0
    Bmin_expected = (mu**2 / g) * sp.exp(-1 / (2 * c * g**2))
    ok_bmin = sp.simplify(Bmin - Bmin_expected) == 0
    ok_vmin = sp.simplify(Vmin + c * g**2 * Bmin**2 / 2) == 0   # V_min = -c g^2 B_min^2/2 < 0

    # imaginary part from the single tachyonic level (n=0, s=-1, M^2 = -gB):
    # Im e2 = (1/2) * (1/2pi) * Integral sqrt(gB - k^2) over |k|<sqrt(gB) = gB/8
    k = sp.Symbol('k', real=True)
    im_e2 = sp.Rational(1, 2) * sp.integrate(sp.sqrt(g * B - k**2),
                                             (k, -sp.sqrt(g * B), sp.sqrt(g * B))) / (2 * sp.pi)
    imV = sp.simplify(g * B / (2 * sp.pi) * im_e2)
    ok_im = sp.simplify(imV - g**2 * B**2 / (16 * sp.pi)) == 0

    return {'zeta_sum_-11/6': ok_sum, 'log_coeff_11/96pi2': ok_coeff,
            'B_min_closed_form': ok_bmin, 'V_min_negative': ok_vmin,
            'Im_V_g2B2_16pi': ok_im,
            'Bmin': sp.sstr(Bmin), 'Vmin': sp.sstr(Vmin)}


