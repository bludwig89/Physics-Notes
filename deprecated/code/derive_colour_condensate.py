t, x, y, z = sp.symbols('t x y z', real=True)
g, B = sp.symbols('g B', positive=True)
gamma = sp.Symbol('gamma', positive=True)
ep = sp.Symbol('epsilon')          # linearisation bookkeeping parameter

COORDS = (t, x, y, z)
ETA = sp.diag(1, -1, -1, -1)       # mostly-minus metric

# SU(2) structure constants eps^{abc} (the a,b,c = 1..3 reduction of F43's f^abc)
def eps3(a, b, c):
    return sp.LeviCivita(a, b, c)


# ------------------------------------------------------------------
# D1 / D1b — Nielsen–Olesen instability from the linearised YM EOM
# ------------------------------------------------------------------
def _ym_field_strength(A):
    """F^a_{mu nu} = d_mu A^a_nu - d_nu A^a_mu + g eps^{abc} A^b_mu A^c_nu.

    A: dict a -> [A^a_t, A^a_x, A^a_y, A^a_z] (sympy expressions).
    Returns F as nested dict F[a][mu][nu] (lower indices)."""
    F = {}
    for a in (1, 2, 3):
        F[a] = [[sp.S.Zero] * 4 for _ in range(4)]
        for mu in range(4):
            for nu in range(4):
                expr = sp.diff(A[a][nu], COORDS[mu]) - sp.diff(A[a][mu], COORDS[nu])
                for b in (1, 2, 3):
                    for c in (1, 2, 3):
                        e = eps3(a, b, c)
                        if e != 0:
                            expr += g * e * A[b][mu] * A[c][nu]
                F[a][mu][nu] = expr
    return F


def _ym_eom(A):
    """E^{nu,a} = d_mu F^{mu nu,a} + g eps^{abc} A^b_mu F^{mu nu,c}  (raised
    with eta).  Returns dict a -> [E^{nu=t..z}]."""
    F = _ym_field_strength(A)
    # raise both indices: F^{mu nu} = eta^{mu alpha} eta^{nu beta} F_{alpha beta}
    Fup = {}
    for a in (1, 2, 3):
        Fup[a] = [[ETA[mu, mu] * ETA[nu, nu] * F[a][mu][nu]
                   for nu in range(4)] for mu in range(4)]
    E = {}
    for a in (1, 2, 3):
        E[a] = []
        for nu in range(4):
            expr = sp.S.Zero
            for mu in range(4):
                expr += sp.diff(Fup[a][mu][nu], COORDS[mu])
                for b in (1, 2, 3):
                    for c in (1, 2, 3):
                        e = eps3(a, b, c)
                        if e != 0:
                            expr += g * e * A[b][mu] * Fup[c][mu][nu]
            E[a].append(expr)
    return E


def derive_D1_nielsen_olesen():
    """Exact growing mode of the linearised YM EOM around constant B."""
    psi = sp.exp(-g * B * (x**2 + y**2) / 4)
    grow = sp.exp(gamma * t)

    results = {}
    for spin_sign, label in ((+1, 'aligned'), (-1, 'anti-aligned')):
        # background (colour-3, symmetric gauge) + charged fluctuation.
        # W_mu = (A^1_mu - i A^2_mu)/sqrt2 with polarisation
        #   eps = (0, 1, i*spin_sign, 0)/sqrt2  -> real fields:
        #   A^1_x = e^{gt} psi,  A^2_y = -spin_sign * e^{gt} psi.
        zero = sp.S.Zero
        A = {
            1: [zero, ep * grow * psi, zero, zero],
            2: [zero, zero, -spin_sign * ep * grow * psi, zero],
            3: [zero, -B * y / 2, B * x / 2, zero],
        }
        E = _ym_eom(A)
        # linearise: O(ep) coefficient of every EOM component
        lin = [sp.expand(sp.diff(comp, ep).subs(ep, 0))
               for a in (1, 2, 3) for comp in E[a]]
        # substitute the dispersion gamma^2 = +gB and check exact closure
        residuals = [sp.simplify(c.subs(gamma, sp.sqrt(g * B))) for c in lin]
        closes = all(r == 0 for r in residuals)
        results[label] = closes
        # for the aligned (unstable) mode also verify it does NOT close at a
        # wrong dispersion, so the certificate is non-vacuous
        if spin_sign == +1:
            wrong = [sp.simplify(c.subs(gamma, sp.sqrt(2 * g * B))) for c in lin]
            results['nonvacuous'] = any(w != 0 for w in wrong)
    return results


def derive_D1b_scalar_control():
    """Charged scalar (minimal coupling, no spin term) on the same Landau
    profile: -D^2 psi = +gB psi exactly  ->  omega^2 = +gB > 0 (stable)."""
    psi = sp.exp(-g * B * (x**2 + y**2) / 4)
    Ax = -B * y / 2
    Ay = B * x / 2
    # D_j = d_j - i g Abar_j acting on the charged scalar
    Dx = sp.diff(psi, x) - sp.I * g * Ax * psi
    Dy = sp.diff(psi, y) - sp.I * g * Ay * psi
    lap = (sp.diff(Dx, x) - sp.I * g * Ax * Dx) + (sp.diff(Dy, y) - sp.I * g * Ay * Dy)
    residual = sp.simplify(-lap - g * B * psi)   # -D^2 psi - gB psi == 0
    return residual == 0


